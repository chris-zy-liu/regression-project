"""Build the report sections from the saved two-stage comparison results."""

import json
from pathlib import Path

import pandas as pd


def build(root):
    output = root / 'results' / 'two_stage'
    summary = json.loads((output / 'summary.json').read_text())
    performance = pd.read_csv(output / 'performance.csv').set_index('model')
    comparisons = pd.read_csv(output / 'paired_tests.csv')
    stage = summary['stage1']
    labels = {'carry_forward': 'Latest adoption rate', 'six_release_mean': 'Recent adoption average',
              'direct': 'Direct ridge', 'two_stage': 'Direct + original predicted counts',
              'two_stage_batch': 'Direct + batch-predicted counts', 'oracle': 'Direct + actual future counts'}
    rows = '\n'.join(f'| {labels[name]} | {row.mae:.3f} | {row.rmse:.3f} | {row.bias:+.3f} |'
                     for name, row in performance.iterrows())
    paired = comparisons[comparisons.block_length == 3]
    paired_rows = '\n'.join(
        f'| {labels[row.model]} vs {labels[row.reference]} | {row.mean_mae_difference:+.3f} | '
        f'{row.wins}/10 | [{row.ci_low:+.3f}, {row.ci_high:+.3f}] |'
        for row in paired.itertuples())
    text = f'''# Milestone 3 comparisons and explanations

Generated by `python two_stage_diagnostics.py`. The experiment uses the same 706
adoption forecasts at ten issue dates, the same ridge learner, and the same earlier
temporal tuning folds for every arm. Forecasts target three Census releases ahead.
This is a retrospective analysis of a fixed October 30, 2026 benchmark catalog.

## 1. Direct and two-stage forecasts

The direct model uses current adoption, history, industry, size, trend, and the
existing control variables. Each two-stage arm adds one predicted release-count
variable. The actual-count arm adds the realized future release count as a
diagnostic using future information. Models are refitted and tuned separately.
The diagnostic tests this particular count input and model specification.

| Adoption forecast | MAE (percentage points) | RMSE (percentage points) | Bias (percentage points) |
|---|---:|---:|---:|
{rows}

The batch arm connects the separate Poisson investigation to adoption forecasting.
It uses the fixed compound Poisson model with time and weekday effects, estimates
batch sizes from earlier provider-day releases, and sums expected model arrivals
through the target survey's reference date. Its specification was developed after
these historical outcomes were known.

| Comparison | Mean change in date-level MAE | Dates improved | Exploratory 95% interval |
|---|---:|---:|---:|
{paired_rows}

Negative differences favor the first model. The displayed intervals resample
three-date blocks together, preserving some local dependence. The saved comparison
also varies block length over two and four dates. Ten forecast dates provide
limited information about uncertainty. These intervals are exploratory.
`paired_tests.csv` is retained as the output filename for compatibility, but its
contents now contain block intervals instead of independence-based p-values.

## 2. What the diagnostic comparisons establish

In this sample, the direct model has lower average adoption error than the tested
release-count extensions. The actual-count arm also fails to reduce average error.
This supports a limited conclusion about this input representation, learner,
forecast horizon, and historical evaluation. It does not establish that every
release predictor must fail, or that businesses do not respond to new models.

Replacing predicted counts with actual counts changes both the feature values
and the fitted regression, including the selected penalty. The resulting error
difference is evidence consistent with first-stage errors contributing to the
loss, but is not an isolated measurement of error propagation. A controlled
follow-up could hold the adoption coefficients fixed while varying the input.

Predicted releases correlate {summary['stage1_signal']['corr_expected_count_with_time']:.2f}
with time across the completed release windows. That is consistent with overlap
with calendar trend information. It does not prove that all release effects are
already captured by the trend. A common release variable can describe shared
nonlinear changes, and interactions can describe different group responses.

The training/test table and the first forecast date identify a possible sensitivity
to regularization. Training error alone does not establish overfitting, especially
when training and test periods have different distributions. The fraction of errors
within two survey standard errors is context about measurement uncertainty, not
a bound on achievable prediction accuracy.

## 3. Release forecast performance

Only windows ending by October 30 are scored. The October 8 issue targets November 1
and is excluded from stage-one accuracy calculations because two future days are
outside the catalog cutoff. Its realized count remains missing in the saved table.
All adoption forecasts have completed release-count windows.

| Release forecast, completed 24-day windows | Average absolute count error |
|---|---:|
| Previous 24-day count | {stage['carry_forward_last24_mae']:.3f} |
| Historical average rate | {stage['historical_average_rate_mae']:.3f} |
| Original Poisson forecast | {stage['poisson_mae']:.3f} |
| Compound Poisson batch forecast | {stage['batch_poisson_mae']:.3f} |

There are {stage['issue_dates']} completed windows. Errors measure models per
24-day window, whose average observed count is {stage['mean_actual_count_24d']:.2f}.
The original forecast's conditional 90% count intervals cover
{stage['coverage_90']:.1%} of these outcomes. The windows overlap, so this coverage
is descriptive. The six nonoverlapping 42-day comparisons are a separate
evaluation with a different horizon. See `poisson_report/` for the batch model's
assumptions, count probabilities, and interval-width comparisons.

Poisson provides a positive-rate model for counts. Its independence and
mean-variance assumptions need checking. Multiple models released by the same
provider on one day motivate compound arrivals. Fractional expected counts are
valid even though realized counts are integers. Simulating counts from estimated
rates describes variation under the assumed model and does not establish a true
minimum possible forecasting error.

## 4. Additional inputs and next comparisons

This experiment varies one count feature at a time. The older
`results/releases/adoption_predictions.csv` experiment also adds benchmark and
capability variables. Chau's breakdown uses that older, broader specification,
so its errors should be labeled separately from this count-only comparison.
The available experiments support continued checks of release timing, capability,
lags, and interactions under matched evaluation. Any practical improvement target
should be agreed before the final evaluation.

## 5. Conclusion for the final report

The direct learner has the lowest average adoption error among these tested
alternatives. Improvements in release-count forecasting do not automatically
produce improvements in adoption prediction, and release-model performance
depends on whether individual models or batches are counted. The batch arm makes
that link explicit in a matched adoption experiment.

Current evidence favors the direct model for this evaluation. The reasons may
include overlap with time trends, first-stage forecast error, limited information
in release counts, and sensitivity to regularization. Some diagnostics support
these explanations, but the comparisons do not identify a unique cause.
The final conclusion should remain specific to the tested models and data.
Historical catalog availability, changing benchmark coverage, survey measurement
error, ten adoption forecast dates, and previously examined outcomes limit
generalization. A later reserved evaluation would strengthen the comparison.

Reproduce with `python two_stage_diagnostics.py`. Predictions, fit records, stage-one
features, interval sensitivity, and the generated text are saved. Seed 403130 plus
block length controls the uncertainty calculations. AI assistance supported the
revision, calculations, and drafting.
'''
    (root / 'docs' / 'M3_REPORT_SECTIONS.md').write_text(text, encoding='utf-8')


if __name__ == '__main__':
    build(Path(__file__).resolve().parent)
